#!/usr/bin/env node
// Generates the Vale term rule and the glossary from style/termbase.yaml.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { parse } from 'yaml';

const TERMBASE = 'style/termbase.yaml';
const RULE = 'vale/AlsoAsked/Terms.yml';
const GLOSSARY = 'docs/glossary.md';
const HEADER = `DO NOT EDIT THIS FILE. It is generated from ${TERMBASE} by tools/build-style.mjs.`;

const { terms } = parse(readFileSync(TERMBASE, 'utf8'));

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function fail(message) {
  console.error(`${TERMBASE}: ${message}`);
  process.exit(1);
}

const seen = new Set();
const swap = {};

for (const entry of terms) {
  for (const key of ['term', 'pos', 'definition', 'example', 'status']) {
    if (!entry[key]) fail(`"${entry.term ?? '?'}" has no "${key}".`);
  }
  if (seen.has(entry.term.toLowerCase())) fail(`"${entry.term}" is in the termbase more than once.`);
  seen.add(entry.term.toLowerCase());

  for (const reject of entry.reject ?? []) {
    if (!['error', 'review'].includes(reject.level)) fail(`"${entry.term}": level must be "error" or "review".`);
    try {
      new RegExp(reject.phrase, 'i');
    } catch (error) {
      fail(`"${entry.term}": "${reject.phrase}" is not a valid regular expression (${error.message}).`);
    }
    if (reject.level === 'error') {
      if (swap[reject.phrase]) fail(`"${reject.phrase}" is rejected by more than one term.`);
      swap[reject.phrase] = reject.use;
    }
  }
}

// Vale substitution rule. Keys are regular expressions. Values are shown in the message.
const ruleLines = [
  `# ${HEADER}`,
  'extends: substitution',
  "message: \"Use '%s', not '%s'. See style/termbase.yaml.\"",
  'level: error',
  'ignorecase: true',
  'swap:',
  ...Object.entries(swap).map(([phrase, use]) => `  '${phrase.replaceAll("'", "''")}': '${use.replaceAll("'", "''")}'`),
  '',
];
write(RULE, ruleLines.join('\n'));

// Glossary, sorted by term.
const sorted = [...terms].sort((a, b) => a.term.localeCompare(b.term, 'en', { sensitivity: 'base' }));
const glossary = [
  '---',
  'title: Glossary',
  'description: The approved term for each concept in the AlsoAsked API documentation.',
  'type: reference',
  '---',
  '',
  `<!-- ${HEADER} -->`,
  '',
  '# Glossary',
  '',
  'This page lists the terms that the AlsoAsked API documentation uses, with the meaning of each term.',
  '',
  '| Term | Meaning | Example |',
  '| --- | --- | --- |',
  // Customers see the definition and the example. Matches and rejected words are for writers only.
  ...sorted.map((entry) => `| ${entry.term} | ${entry.definition.trim().replaceAll('|', '\\|')} | ${entry.example.replaceAll('|', '\\|')} |`),
  '',
];
write(GLOSSARY, glossary.join('\n'));

const drafts = terms.filter((entry) => entry.status === 'draft').length;
console.log(`${terms.length} terms (${drafts} draft), ${Object.keys(swap).length} Vale substitutions.`);
